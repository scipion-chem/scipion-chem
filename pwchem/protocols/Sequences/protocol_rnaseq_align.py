import os
import re
import shlex
import shutil

from pyworkflow.protocol.params import (
    BooleanParam, EnumParam, IntParam, PointerParam, StringParam
)
from pwem.protocols import EMProtocol

from pwchem import Plugin
from pwchem.constants import RNASEQ_DIC
from pwchem.objects import AlignmentFile
from pwchem.utils.utilsRNA import GATKPreparationMixin


class ProtRNASeqAlignment(EMProtocol):
    """
    Align RNA-seq reads against a reference genome using STAR or HISAT2.

    This protocol performs the main alignment step of an RNA-seq workflow.
    It accepts a FastqFile object containing either single-end or paired-end
    sequencing reads and aligns them against a selected reference genome from
    a SetOfGenomes object using STAR or HISAT2.

    Retained genome indexes are reused only when their recorded input paths,
    sizes, modification times and relevant index parameters match. This
    comparison does not compute reference checksums. Changed or unrecorded
    index inputs trigger a rebuild in the protocol directory.

    The protocol automatically builds the genome index required by the selected
    aligner, performs the alignment, sorts the resulting alignments by genomic
    coordinate, creates a BAM index and extracts basic mapping statistics. The
    final result is stored as an AlignmentFile object that can be used by
    downstream Scipion protocols.

    ----------------------------
    Input reads
    ----------------------------

    inputFastq : FastqFile
        Input RNA-seq reads represented as a Scipion FastqFile object.

        Both single-end and paired-end datasets are supported. The sequencing
        type is obtained directly from the FastqFile object, so it does not need
        to be specified again in this protocol.

        For paired-end datasets, both read files stored in the FastqFile object
        are passed to the selected aligner.

    ----------------------------
    Reference genome
    ----------------------------

    inputGenomes : SetOfGenomes
        Set of reference genomes generated by a compatible Scipion protocol,
        such as Reference genomes or Import genomes.

        If the set contains more than one Genome object, the genomeIndex
        parameter determines which genome is used for the alignment.

        The selected Genome object may provide:

        - Reference genome FASTA file.
        - GTF annotation file.
        - Scientific name.
        - Genome assembly.
        - Genome release or accession.
        - Reference source.

        The FASTA file is required. The GTF annotation is optional.

    genomeIndex : int
        Index of the Genome object selected from the input SetOfGenomes.
        The genome can be selected using the associated wizard.

    ----------------------------
    Alignment programs
    ----------------------------

    Two RNA-seq aligners are supported:

    STAR
        STAR is a splice-aware aligner designed for RNA-seq data.

        Before alignment, a STAR genome index is generated from the selected
        reference FASTA file. If a GTF annotation is available, it is included
        during index generation to provide known splice-junction information.

        The sjdbOverhang parameter can be specified manually. When set to 0,
        the protocol automatically uses:

            read length - 1

        based on the mean read length stored in the input FastqFile object.
        If a valid read length is not available, a default value of 100 is used.

        The sjdbOverhang parameter is used during STAR genome index generation
        when a GTF annotation is available.

    ----------------------------
    STAR alignment parameters
    ----------------------------

    These options are displayed and applied only when STAR is selected.
    Their defaults match the RNA-seq workflow configuration.

    starOutFilterMultimapNmax : int, default 10
        Maps to --outFilterMultimapNmax. Reads mapping to more than this
        number of loci are discarded. The value must be positive.

    starOutSAMstrandField : enum, default intronMotif
        Maps to --outSAMstrandField. Choices are None and intronMotif.
        intronMotif adds the XS strand tag and filters alignments with
        inconsistent or non-canonical introns. This is distinct from the
        RNA library strandness parameter used by HISAT2.

    starOutReadsUnmapped : enum, default Fastx
        Maps to --outReadsUnmapped. Choices are None and Fastx.
        Fastx writes unmapped reads to star_Unmapped.out.mate1 and, for
        paired-end input, star_Unmapped.out.mate2 in the extra directory.
        These auxiliary files are not published as separate FastqFile objects.

    starOutSAMunmapped : enum, default Within
        Maps to --outSAMunmapped. Choices are None, Within and Within KeepPairs.
        Within includes unmapped reads in the BAM. Within KeepPairs also
        retains unmapped mates with mapped alignments. This option is
        independent of writing unmapped reads to Fastx files.

    starOutSAMattributes : str, default NH HI NM MD AS
        Maps to --outSAMattributes. Specify space-separated SAM tags or
        one STAR preset: None, Standard or All. The default requests the
        mapping count (NH), alignment index (HI), edit distance (NM),
        reference mismatch information (MD) and alignment score (AS).
        Preflight validation checks tag syntax; STAR checks whether the
        requested tags are supported.

    ----------------------------
    HISAT2 alignment
    ----------------------------

    HISAT2
        HISAT2 is a splice-aware alignment program based on a hierarchical
        indexing strategy.

        A HISAT2 index is generated from the reference FASTA file before
        alignment.

        The --dta option can optionally be enabled to generate alignments
        suitable for downstream transcriptome reconstruction and assembly.

        Library strandness is passed to HISAT2 when requested. STAR does not use
        this parameter during alignment.

    ----------------------------
    Genome indexing
    ----------------------------

    A genome index is automatically generated according to the selected aligner:

    - STAR creates a STAR genome index directory.
    - HISAT2 creates the corresponding HISAT2 index files.

    The number of threads selected in the protocol is used during both genome
    index generation and read alignment.

    By default, genome index files are removed after successful execution to
    reduce disk usage. They can be preserved by enabling the
    keepIntermediateFiles option.

    ----------------------------
    Alignment output
    ----------------------------

    Both aligners ultimately produce a coordinate-sorted BAM file.

    For STAR, coordinate sorting is requested directly during alignment.

    For HISAT2, the SAM output generated by HISAT2 is piped directly to
    samtools sort to create a coordinate-sorted BAM file without keeping an
    intermediate SAM file.

    After alignment, samtools index is used to generate the corresponding
    BAI index.

    The protocol verifies that the BAM file exists and is not empty before
    creating the final output object.

    ----------------------------
    Alignment statistics
    ----------------------------

    Basic alignment statistics are extracted from the reports generated by
    STAR or HISAT2.

    The reported statistics include:

    - Total reads.
    - Mapped reads.
    - Uniquely mapped reads.
    - Multi-mapped reads.
    - Unmapped reads.
    - Overall mapping rate.
    - Unique mapping rate.
    - Multi-mapping rate.
    - Unmapped rate.

    STAR statistics are obtained from the STAR final log file. For HISAT2
    paired-end data, mapped, unique and multi-mapped counts describe
    concordantly aligned pairs. Their rates use the total number of pairs,
    keeping counts and percentages consistent. Discordant and separately
    mapped mates contribute to the raw HISAT2 overall rate in its log, not
    to these concordant-pair counts.

    HISAT2 statistics are extracted from the alignment summary written to
    standard error.

    In addition, samtools flagstat is executed on the final BAM file to provide
    additional alignment-level information. For single-end datasets, it may
    be used as a fallback when total or mapped read counts cannot be obtained
    from the aligner-specific report.

    ----------------------------
    Output
    ----------------------------

    outputAlignment : AlignmentFile
        Coordinate-sorted and indexed RNA-seq alignment.

        The output AlignmentFile stores:

        - BAM file path.
        - BAI index path.
        - Alignment format.
        - Sample name.
        - Aligner used.
        - Reference FASTA file.
        - Reference GTF file, when available.
        - Reference name.
        - Reference source.
        - Reference scientific name and assembly as structured metadata.
        - Alignment command.
        - Aligner log file.
        - Sorting and indexing status.
        - Mapping statistics.

        Source relations are established between the AlignmentFile and both
        the input FastqFile and the input SetOfGenomes.

    ----------------------------
    Validation
    ----------------------------

    Before execution, the protocol validates that:

    - An input FastqFile object has been provided.
    - FASTQ files exist on disk.
    - Paired-end datasets contain both read files.
    - A SetOfGenomes object has been provided.
    - The SetOfGenomes is not empty.
    - The selected genome index is valid.
    - The selected Genome contains a reference FASTA file.
    - The reference FASTA file exists.
    - The optional GTF file exists when provided.
    - When STAR is selected, sjdbOverhang is 0 or a positive integer.
    - When STAR is selected, the maximum mapping loci value is positive.
    - When STAR is selected, SAM attributes contain two-character tags or
      a single supported preset name (None, Standard or All).

    Execution is stopped if any required input file or reference information
    is missing.

    ----------------------------
    Notes
    ----------------------------

    - STAR, HISAT2 and samtools must be available in the RNA-seq software
      environment configured by the plugin.
    - FASTQ compression is detected from the input FastqFile object. STAR uses
      zcat automatically for compressed input files.
    - The reference GTF file is optional. STAR can use it during genome index
      generation when available.
    - Genome indexes can require substantial disk space, particularly for large
      eukaryotic genomes.
    - Intermediate genome indexes are removed by default after successful
      execution.
    - Reference genomes must be provided as Scipion objects. Local reference
      files should first be imported using the Import genomes protocol.
    - The resulting AlignmentFile is intended to serve as the input for
      downstream RNA-seq analysis protocols in Scipion.
    """
    # -------------------------------------------------------
    # Constants
    # -------------------------------------------------------

    INDEX_MANIFEST = 'index_inputs.json'
    ALIGN_STAR = 0
    ALIGN_HISAT2 = 1
    ALIGNER_CONDITION = 'aligner == %d'

    STAR_STRAND_FIELDS = ['None', 'intronMotif']
    STAR_UNMAPPED_READS = ['None', 'Fastx']
    STAR_UNMAPPED_BAM = ['None', 'Within', 'Within KeepPairs']

    _label = 'RNA-seq alignment'

    # -------------------------------------------------------
    # Parameters
    # -------------------------------------------------------

